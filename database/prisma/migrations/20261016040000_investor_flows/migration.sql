CREATE TABLE `investor_flow_daily` (
 `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 `target_type` VARCHAR(12) NOT NULL,
 `target_key` VARCHAR(20) NOT NULL,
 `trade_date` DATE NOT NULL,
 `investor_code` VARCHAR(32) NOT NULL,
 `investor_name` VARCHAR(64) NOT NULL,
 `source` VARCHAR(32) NOT NULL,
 `exchange_scope` VARCHAR(24) NOT NULL,
 `buy_amount` DECIMAL(32,4) NULL,
 `sell_amount` DECIMAL(32,4) NULL,
 `net_amount` DECIMAL(32,4) NULL,
 `buy_quantity` DECIMAL(32,4) NULL,
 `sell_quantity` DECIMAL(32,4) NULL,
 `net_quantity` DECIMAL(32,4) NULL,
 `amount_unit` VARCHAR(24) NULL,
 `quantity_unit` VARCHAR(24) NULL,
 `publication_status` VARCHAR(24) NOT NULL,
 `reason` VARCHAR(500) NULL,
 `raw` JSON NOT NULL,
 `collected_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 `updated_at` DATETIME(3) NOT NULL,
 PRIMARY KEY (`id`),
 UNIQUE INDEX `investor_flow_identity` (`target_type`,`target_key`,`trade_date`,`source`,`exchange_scope`,`investor_code`),
 INDEX `investor_flow_daily_target_type_target_key_trade_date_idx` (`target_type`,`target_key`,`trade_date`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `live_price_alerts` (
 `identity_key` VARCHAR(160) NULL,
 `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 `user_id` BIGINT UNSIGNED NOT NULL,
 `security_id` BIGINT UNSIGNED NOT NULL,
 `market` VARCHAR(8) NOT NULL,
 `direction` VARCHAR(8) NOT NULL,
 `amount` DECIMAL(20,0) NOT NULL,
 `enabled` BOOLEAN NOT NULL DEFAULT true,
 `paused_until` DATETIME(3) NULL,
 `eligible_after` DATETIME(3) NOT NULL,
 `inside` BOOLEAN NULL,
 `last_observed_at` DATETIME(3) NULL,
 `last_sequence` VARCHAR(32) NULL,
 `version` INTEGER NOT NULL DEFAULT 1,
 `deleted_at` DATETIME(3) NULL,
 `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 `updated_at` DATETIME(3) NOT NULL,
 PRIMARY KEY (`id`),
 UNIQUE INDEX `live_price_alerts_identity_key_key` (`identity_key`),
 INDEX `live_price_alerts_user_id_deleted_at_id_idx` (`user_id`,`deleted_at`,`id`),
 INDEX `live_price_alerts_enabled_deleted_at_market_security_id_idx` (`enabled`,`deleted_at`,`market`,`security_id`),
 CONSTRAINT `live_price_alerts_user_id_fkey` FOREIGN KEY (`user_id`) REFERENCES `auth_users` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE TABLE `live_price_alert_events` (
 `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
 `user_id` BIGINT UNSIGNED NOT NULL,
 `condition_id` BIGINT UNSIGNED NOT NULL,
 `open_key` VARCHAR(64) NULL,
 `security_id` BIGINT UNSIGNED NOT NULL,
 `market` VARCHAR(8) NOT NULL,
 `direction` VARCHAR(8) NOT NULL,
 `amount` DECIMAL(20,0) NOT NULL,
 `price` DECIMAL(20,0) NOT NULL,
 `change` DECIMAL(20,0) NOT NULL,
 `rate` DECIMAL(12,6) NOT NULL,
 `observed_at` DATETIME(3) NOT NULL,
 `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 `acknowledged_at` DATETIME(3) NULL,
 PRIMARY KEY (`id`),
 UNIQUE INDEX `live_price_alert_events_open_key_key` (`open_key`),
 INDEX `live_price_alert_events_user_id_acknowledged_at_id_idx` (`user_id`,`acknowledged_at`,`id`),
 CONSTRAINT `live_price_alert_events_user_id_fkey` FOREIGN KEY (`user_id`) REFERENCES `auth_users` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
 CONSTRAINT `live_price_alert_events_condition_id_fkey` FOREIGN KEY (`condition_id`) REFERENCES `live_price_alerts` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
